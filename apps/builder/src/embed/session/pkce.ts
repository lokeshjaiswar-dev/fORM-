/*
 * PKCE pieces and ids for the session client (SEC-DESIGN 1.3, 1.7): a random verifier, its S256 challenge, a request id.
 * No storage, no network. `crypto.subtle` exists only in secure contexts (https, localhost); a DMS on an http LAN address has
 * none, so SHA-256 falls back to a small pure implementation (checked against the contract fixture pairs and RFC 7636).
 */

export function base64url(bytes: Uint8Array): string {
  let bin = '';
  for (const b of bytes) bin += String.fromCharCode(b);
  return btoa(bin).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}

function randomBytes(n: number): Uint8Array {
  const out = new Uint8Array(n);
  globalThis.crypto.getRandomValues(out);
  return out;
}

/** A PKCE verifier: 32 random bytes, base64url, 43 characters. Lives in memory only. */
export function newVerifier(): string {
  return base64url(randomBytes(32));
}

/** A UUID v4 for `X-Request-Id`. */
export function newRequestId(): string {
  const c = globalThis.crypto;
  if (typeof c.randomUUID === 'function') return c.randomUUID();
  const b = randomBytes(16);
  b[6] = ((b[6] ?? 0) & 0x0f) | 0x40;
  b[8] = ((b[8] ?? 0) & 0x3f) | 0x80;
  const h = [...b].map((x) => x.toString(16).padStart(2, '0')).join('');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}

