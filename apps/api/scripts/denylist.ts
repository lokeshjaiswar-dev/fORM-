import { readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { PASSWORD_MIN_LENGTH } from '../src/modules/auth/passwords.ts';

/**
 * Regenerates `src/modules/auth/denylist.data.ts`, the local list of common passwords every edition checks
 * (architecture §3.3: "local top-100k password list everywhere"), from a newline-separated source list:
 *
 *   curl -sSfLO https://raw.githubusercontent.com/danielmiessler/SecLists/master/Passwords/Common-Credentials/100k-most-used-passwords-NCSC.txt
 *   pnpm --filter @form/api exec tsx scripts/denylist.ts 100k-most-used-passwords-NCSC.txt
 *
 * The source is the NCSC top 100,000 (from Have I Been Pwned, via SecLists, MIT). Entries shorter than the minimum
 * length are dropped, because the length rule refuses them anyway; the rest are lower-cased, de-duplicated and sorted.
 */
const source = process.argv[2];
if (!source) {
  process.stderr.write('usage: tsx scripts/denylist.ts <list.txt>\n');
  process.exit(1);
}
const entries = [
  ...new Set(
    readFileSync(source, 'utf8')
      .split(/\r?\n/)
      .map((l) => l.toLowerCase())
      .filter((l) => [...l].length >= PASSWORD_MIN_LENGTH),
  ),
].sort();
const gz = gzipSync(entries.join('\n'), { level: 9 }).toString('base64');
const target = new URL('../src/modules/auth/denylist.data.ts', import.meta.url);
writeFileSync(
  target,
  [
    '// Generated by scripts/denylist.ts from the NCSC top 100,000 (Have I Been Pwned, via SecLists, MIT). Do not edit.',
    `export const DENYLIST_ENTRIES = ${entries.length};`,
    `export const DENYLIST_GZIP = '${gz}';`,
    '',
  ].join('\n'),
);
process.stdout.write(`denylist: ${entries.length} entries, ${gz.length} base64 characters\n`);
