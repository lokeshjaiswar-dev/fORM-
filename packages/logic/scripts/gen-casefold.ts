import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Generates src/casefold.generated.ts from the Unicode CaseFolding.txt in scripts/data (statuses C and S:
 * simple case folding). The Unicode version matches the pinned grapheme segmenter (@form/i18n).
 *
 *   node scripts/gen-casefold.ts           rewrite the table
 *   node scripts/gen-casefold.ts --check   fail if the committed table is out of date
 */

const UNICODE_VERSION = '17.0.0';
const SOURCE_SHA256 = 'ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.join(here, 'data', `CaseFolding-${UNICODE_VERSION}.txt`);
const target = path.join(here, '..', 'src', 'casefold.generated.ts');

const text = readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
const digest = createHash('sha256').update(text).digest('hex');
if (digest !== SOURCE_SHA256) {
  console.error(`${path.basename(source)}: sha256 ${digest}, expected ${SOURCE_SHA256}`);
  process.exit(1);
}

const pairs: Array<[number, number]> = [];
for (const line of text.split('\n')) {
  const data = line.split('#')[0]?.trim();
  if (!data) continue;
  const [code, status, mapping] = data.split(';').map((f) => f.trim());
  if (status !== 'C' && status !== 'S') continue;
  if (code === undefined || mapping === undefined || mapping.includes(' ')) throw new Error(`unexpected line: ${line}`);
  pairs.push([Number.parseInt(code, 16), Number.parseInt(mapping, 16)]);
}
pairs.sort((a, b) => a[0] - b[0]);

/* Runs of [start, count, delta, stride]: `count` code points start, start+stride, … each fold to cp + delta. */
const runs: Array<[number, number, number, number]> = [];
for (const [from, to] of pairs) {
  const last = runs.at(-1);
  if (last && to - from === last[2]) {
    const gap = from - (last[0] + (last[1] - 1) * last[3]);
    if (last[1] === 1 && (gap === 1 || gap === 2)) {
      last[1] = 2;
      last[3] = gap;
      continue;
    }
    if (last[1] > 1 && gap === last[3]) {
      last[1] += 1;
      continue;
    }
  }
  runs.push([from, 1, to - from, 1]);
}

const hex = (n: number) => `0x${n.toString(16)}`;
const body = runs.map(([start, count, delta, stride]) => `  ${hex(start)}, ${count}, ${delta}, ${stride},`).join('\n');
const output = `/* Generated by scripts/gen-casefold.ts from CaseFolding-${UNICODE_VERSION}.txt (statuses C + S). Do not edit. */

export const CASE_FOLD_UNICODE_VERSION = '${UNICODE_VERSION}';

/** ${pairs.length} mappings as runs of [start, count, delta, stride]. */
export const CASE_FOLD_RUNS: readonly number[] = [
${body}
];
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    current = '';
  }
  if (current !== output) {
    console.error('src/casefold.generated.ts is out of date. Run `pnpm --filter @form/logic casefold`.');
    process.exit(1);
  }
  console.log(`Case-fold table is up to date (${pairs.length} mappings, ${runs.length} runs).`);
} else {
  writeFileSync(target, output);
  console.log(`Wrote ${path.relative(process.cwd(), target)} (${pairs.length} mappings, ${runs.length} runs).`);
}
